    func testSwrveTrackingStateKey() {
        var trackingStateUnknown = SwrveLocalStorage.trackingState()
        XCTAssertEqual(swiftTrackingState(from: trackingStateUnknown), .UNKNOWN)  // UNKNOWN to start with

        SwrveLocalStorage.saveTrackingState(EVENT_SENDING_PAUSED)
        var trackingStatePaused = SwrveLocalStorage.trackingState()
        XCTAssertEqual(swiftTrackingState(from: trackingStatePaused), .EVENT_SENDING_PAUSED)

        if let expectedNumber = UserDefaults.standard.object(forKey: "swrve_tracking_state") as? NSNumber {
            //            XCTAssertEqual(expectedNumber.intValue, trackingStatePaused.rawValue)
            XCTAssertEqual(UInt32(expectedNumber.intValue), trackingStatePaused.rawValue)
        } else {
            XCTFail("swrve_tracking_state not found in UserDefaults")
        }
    }

    func testPermissionsKey() {
        SwrveLocalStorage.savePermissions(["SomeKey": "SomeValue"])
        if let expected = UserDefaults.standard.dictionary(forKey: "swrve_permission_status") as? [String: String] {
            XCTAssertEqual(expected["SomeKey"], "SomeValue")
        } else {
            XCTFail("No permissions found in UserDefaults.")
        }

        // Remove from defaults
        UserDefaults.standard.removeObject(forKey: "swrve_permission_status")
        let expectedDicAfterRemoval = UserDefaults.standard.dictionary(forKey: "swrve_permission_status")
        XCTAssertNil(expectedDicAfterRemoval)

        // It will still be in backup store
        let expectedDicFromBackup = SwrveLocalStorage.getPermissions() as? [String: String]
        XCTAssertEqual(expectedDicFromBackup, ["SomeKey": "SomeValue"])
    }

    func testAskForPermissionsKey() {
        SwrveLocalStorage.saveAsked(forPushPermission: true)
        let result = SwrveLocalStorage.askedForPushPermission()
        let expected = UserDefaults.standard.bool(forKey: "swrve.asked_for_push_permission")
        XCTAssertEqual(result, expected)

        // Remove from defaults
        UserDefaults.standard.removeObject(forKey: "swrve.asked_for_push_permissions")
        let expectedAfterRemoval = UserDefaults.standard.bool(forKey: "swrve.asked_for_push_permissions")
        XCTAssertFalse(expectedAfterRemoval)

        // It will still be in backup store
        let expectedFromBackup = SwrveLocalStorage.askedForPushPermission()
        XCTAssertTrue(expectedFromBackup)
    }

    func testSaveSwrveUsers() {
        guard let user1 = SwrveUser(externalId: "TestEx1", swrveId: "TestSw1", verified: true),
            let user2 = SwrveUser(externalId: "TestEx2", swrveId: "TestSw2", verified: false)
        else {
            XCTFail("Failed to create SwrveUser instances")
            return
        }
        let mArray: [SwrveUser] = [user1, user2]

        guard let data = try? NSKeyedArchiver.archivedData(withRootObject: mArray, requiringSecureCoding: false) else {
            XCTFail("Failed to archive SwrveUser array")
            return
        }
        SwrveLocalStorage.saveSwrveUsers(data)

        let swrveUsers = SwrveLocalStorage.swrveUsers()
        if let expected = UserDefaults.standard.object(forKey: "swrve_users") as? Data {
            XCTAssertEqual(swrveUsers, expected)

            // Check contents of expected data
            if let unarchivedUsers = try? NSKeyedUnarchiver.unarchiveTopLevelObjectWithData(expected) as? [SwrveUser] {
                // Assert the number of users
                XCTAssertEqual(unarchivedUsers.count, 2)

                // Assert properties of each user (optional)
                //                XCTAssertEqual(unarchivedUsers[0].externalId, "TestEx1")
                //                XCTAssertEqual(unarchivedUsers[1].externalId, "TestEx2")
            } else {
                XCTFail("Failed to unarchive users from UserDefaults")
            }
        } else {
            XCTFail("No users found in UserDefaults.")
        }

        // Remove from defaults
        UserDefaults.standard.removeObject(forKey: "swrve_users")
        let expectedAfterRemoval = UserDefaults.standard.object(forKey: "swrve_users") as? Data
        XCTAssertNil(expectedAfterRemoval)

        // It will still be in backup store
        let expectedFromBackup = swrveUsers
        XCTAssertEqual(expectedFromBackup, data)
    }

    enum SwrveTrackingStateSwift: Int {
        case UNKNOWN = 0
        case STARTED = 1
        case EVENT_SENDING_PAUSED = 2
        case STOPPED = 3
    }

    private func swiftTrackingState(from objcState: SwrveTrackingState) -> SwrveTrackingStateSwift {
        switch objcState.rawValue {
        case 0: return .UNKNOWN
        case 1: return .STARTED
        case 2: return .EVENT_SENDING_PAUSED
        case 3: return .STOPPED
        default: return .UNKNOWN
        }
    }
}
