import XCTest

class SwrveTestLocalStorage: XCTestCase {

    override func setUp() {
        super.setUp()
        SwrveTestHelper.setUp()
    }

    override func tearDown() {
        super.tearDown()
        SwrveTestHelper.tearDown()
    }

    func testApplicationSupportCreatesNewFile() {
        let fileManager = FileManager.default
        if let appSupportDir = SwrveLocalStorage.applicationSupportPath() {
            XCTAssertTrue(fileManager.fileExists(atPath: appSupportDir), "File is not generated by Application Support")
        } else {
            XCTFail("testApplicationSupportCreatesNewFile: Application Support path is nil")
        }
    }

    func testApplicationSupportDoesntOverride() {
        let path = [SwrveLocalStorage.applicationSupportPath(), "testFile"].joined(separator: "/")
        try? "[]".write(toFile: path, atomically: true, encoding: .utf8)

        // Call path again, and then check if the written file is still present and unaltered
        let path2 = [SwrveLocalStorage.applicationSupportPath(), "testFile"].joined(separator: "/")
        let content = try? String(contentsOfFile: path2, encoding: .utf8)

        XCTAssertEqual(content, "[]", "testApplicationSupportDoesntOverride: \(String(describing: content)) does not equal '[]'")
    }

    func testFlushFrequencyKey() {
        SwrveLocalStorage.saveFlushFrequency(999)
        let result = SwrveLocalStorage.flushFrequency()
        let expected = UserDefaults.standard.double(forKey: "swrve_cr_flush_frequency")
        XCTAssertTrue(result == expected)

        // Remove from defaults
        UserDefaults.standard.removeObject(forKey: "swrve_cr_flush_frequency")
        let resultAfterRemoval = UserDefaults.standard.double(forKey: "swrve_cr_flush_frequency")
        XCTAssertTrue(resultAfterRemoval == 0)

        // It will still be in backup store
        let resultFromBackup = SwrveLocalStorage.flushFrequency()
        XCTAssertTrue(resultFromBackup == 999)
    }

    func testFlushDelayKey() {
